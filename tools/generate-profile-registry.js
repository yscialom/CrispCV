const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const configDir = path.join(__dirname, '../config');
const outputDir = path.join(__dirname, '../src/app/core');
const outputFile = path.join(outputDir, 'profile.registry.ts');

let version = 'unknown';
try {
  version = execSync('git describe --tags --always', { stdio: ['ignore', 'pipe', 'ignore'] })
    .toString()
    .trim();
} catch (e) {
  version = process.env['APP_VERSION'] || 'v0.0.0';
}

const profileFiles = fs
  .readdirSync(configDir)
  .filter((file) => file.startsWith('profile.') && file.endsWith('.ts'));

const locales = profileFiles
  .map((file) => {
    const match = file.match(/profile\.(.*)\.ts/);
    return match ? match[1] : null;
  })
  .filter(Boolean);

let imports = '';
let profileMap = 'export const PROFILES: Record<string, Resume> = {\n';

locales.forEach((locale) => {
  const variableName = locale.replace(/[^a-zA-Z0-9]/g, '_');
  imports += `import { PROFILE_CONFIG as ${variableName} } from '../../../config/profile.${locale}';\n`;
  profileMap += `  '${locale}': ${variableName},\n`;
});

profileMap += '};\n';

const content = `// This file is auto-generated by tools/generate-profile-registry.js
import { Resume } from './models/resume.models';
${imports}
${profileMap}
export const SUPPORTED_LANGUAGES = [${locales.map((l) => `'${l}'`).join(', ')}];
export const VERSION = '${version}';
`;

if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

fs.writeFileSync(outputFile, content);
console.log(`Generated ${outputFile} with ${locales.length} profiles: ${locales.join(', ')}`);
